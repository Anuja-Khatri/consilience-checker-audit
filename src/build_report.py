"""build_report: generate the numbers lock and the per-checker certificates
from the receipts, and a coverage skeleton for results/REPORT.md.

Numbers come only from receipts (mechanical). The new-vs-known classification,
severity and fix for each finding come from a curated findings.yaml, so human
judgement is separated from the mechanical counts. Run after all contracts are
frozen and run.

    python -I src/build_report.py
"""
from __future__ import annotations

import glob
import json
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MLEB_RECEIPTS = sorted(glob.glob(str(ROOT / "results/receipts/MLEB/*/receipt.json")))
SE_RECEIPTS = sorted(glob.glob(str(ROOT / "results/receipts/SE/*/receipt.json")))
FINDINGS_FILE = ROOT / "results/findings.yaml"


def load(p):
    return json.loads(Path(p).read_text())


def mleb_rows():
    rows = []
    for rp in MLEB_RECEIPTS:
        r = load(rp)
        blocks = [c for c in r["checks"] if c["verdict"] == "BLOCK"]
        rows.append({
            "checker": r["competition_id"], "kind": "mle-bench grader", "verdict": r["verdict"],
            "n_checks": len(r["checks"]), "n_block": len(blocks),
            "blocks": [c["check"] for c in blocks], "labels": r.get("labels", []),
            "receipt": str(Path(rp).relative_to(ROOT)),
        })
    return rows


def se_rows():
    rows = []
    for rp in SE_RECEIPTS:
        r = load(rp)
        blocks = [p for p in r["probes"] if p["verdict"] == "BLOCK"]
        rows.append({
            "checker": f"simple-evals/{r['eval']}", "kind": "simple-evals extractor", "verdict": r["verdict"],
            "n_checks": len(r["probes"]), "n_block": len(blocks),
            "blocks": [p["label"] for p in blocks], "labels": r.get("labels", []),
            "receipt": str(Path(rp).relative_to(ROOT)),
        })
    return rows


def build_numbers(mleb, se):
    def tally(rows):
        return {
            "n_contracts": len(rows),
            "n_holds": sum(r["verdict"] == "HOLDS" for r in rows),
            "n_breaks": sum(r["verdict"] == "BREAKS" for r in rows),
            "n_partial": sum(r["verdict"] == "PARTIAL" for r in rows),
            "n_block_findings": sum(r["n_block"] for r in rows),
            "breaks": sorted(r["checker"] for r in rows if r["verdict"] == "BREAKS"),
        }
    findings = {}
    if FINDINGS_FILE.exists():
        findings = yaml.safe_load(FINDINGS_FILE.read_text()) or {}
    f_list = findings.get("findings", [])
    numbers = {
        "generated": str(date.today()),
        "note": "Every public number is registered here with its n. The report and certificates read from this file.",
        "mleb_leg": tally(mleb),
        "simple_evals_leg": tally(se),
        "findings_classified": {
            "total_confirmed": len(f_list),
            "new": sum(1 for f in f_list if f.get("status") == "new"),
            "confirmation_of_known": sum(1 for f in f_list if f.get("status") == "known"),
        },
    }
    (ROOT / "results/numbers.lock.yaml").write_text(
        "# AUTO-GENERATED by src/build_report.py from the receipts and results/findings.yaml. Do not edit by hand.\n"
        + yaml.safe_dump(numbers, sort_keys=False))
    return numbers


def write_certificate(row, receipt):
    cid = row["checker"].replace("/", "_")
    lines = [f"---",
             f"checker: {row['checker']}",
             f"kind: {row['kind']}",
             f"source: {receipt['source'].get('repo')} @ {receipt['source'].get('commit')}",
             f"verdict: {row['verdict']}",
             f"checks_run: {row['n_checks']}",
             f"blocks: {row['n_block']}",
             f"receipt: {row['receipt']}",
             f"---", "",
             f"# Certificate: {row['checker']}", "",
             f"**Verdict: {row['verdict']}** on the checks run. A verdict is read with its coverage below.", "",
             "## Scope",
             f"- Checker: `{row['checker']}` ({row['kind']}).",
             f"- Source: {receipt['source'].get('repo')} at commit `{receipt['source'].get('commit')}`.",
             f"- Contract author: {receipt.get('contract_author','model')} (drafted by an AI assistant, read before use).", "",
             "## Checks run"]
    if "checks" in receipt:
        for c in receipt["checks"]:
            lines.append(f"- `{c['check']}`: **{c['verdict']}**. {c['detail']}")
    else:
        for p in receipt["probes"]:
            lines.append(f"- {p['label']}: **{p['verdict']}** (expected_correct={p['expected_correct']}, observed={p['observed_correct']})")
    lines += ["", "## Limits", f"- {receipt.get('limits','')}",
              "- A HOLDS is evidence on the checks run at this commit, not a proof of correctness.", ""]
    if row["labels"]:
        lines += [f"## Known public issues referenced", f"- {', '.join(row['labels'])} (see LABELS.yaml)", ""]
    out = ROOT / "results/certificates" / f"{cid}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))


def main():
    mleb, se = mleb_rows(), se_rows()
    numbers = build_numbers(mleb, se)
    for rp in MLEB_RECEIPTS + SE_RECEIPTS:
        r = load(rp)
        row = next(x for x in (mleb + se) if x["receipt"] == str(Path(rp).relative_to(ROOT)))
        write_certificate(row, r)
    print("numbers.lock.yaml:")
    print(yaml.safe_dump(numbers, sort_keys=False))
    print(f"certificates written: {len(mleb)+len(se)}")
    print("\nMLE-bench coverage:")
    for r in mleb:
        print(f"  {r['verdict']:8s} {r['checker']}  blocks={r['blocks']}")
    print("simple-evals coverage:")
    for r in se:
        print(f"  {r['verdict']:8s} {r['checker']}  blocks={len(r['blocks'])}")


if __name__ == "__main__":
    main()
